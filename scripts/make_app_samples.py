def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def pick_defects(defects: list, n: int) -> list:
    """Round-robin over sorted defect types, lowest-numbered image first."""
    by_type: dict[str, list] = {}
    for s in sorted(defects, key=lambda s: (s.defect_type, s.path.name)):
        by_type.setdefault(s.defect_type, []).append(s)
    picks, i = [], 0
    while len(picks) < n and any(by_type.values()):
        t = sorted(by_type)[i % len(by_type)]
        if by_type[t]:
            picks.append(by_type[t].pop(0))
        i += 1
    return picks


def save(src: Path, dst: Path) -> tuple[str, str]:
    im = Image.open(src)
    orig = f"{im.width}x{im.height}"
    im = im.convert("L") if im.mode in ("L", "I;16") else im.convert("RGB")
    scale = MAX_SIDE / max(im.size)
    if scale < 1:
        im = im.resize((round(im.width * scale), round(im.height * scale)), Image.LANCZOS)
    dst.parent.mkdir(parents=True, exist_ok=True)
    im.save(dst, quality=JPEG_QUALITY, optimize=True)
    return orig, f"{im.width}x{im.height}"


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    ap = argparse.ArgumentParser(description="Build app/samples from MVTec AD")
    ap.add_argument("--data-root", default="data/mvtec_ad")
    ap.add_argument("--out", type=Path, default=Path("app/samples"))
    ap.add_argument("--categories", nargs="+", default=["bottle", "screw"])
    ap.add_argument("--n-defects", type=int, default=4)
    args = ap.parse_args()

    if args.out.exists():
        shutil.rmtree(args.out)
    rows = []
    for cat in args.categories:
        data = load_category(args.data_root, cat)
        goods = [s for s in data.test if s.label == 0][:2]
        items = [("refs", 0, "good", p) for p in data.train_paths[:4]]
        items += [("tests", 0, "good", s.path) for s in goods]
        items += [("tests", 1, s.defect_type, s.path) for s in pick_defects([s for s in data.test if s.label], args.n_defects)]
        for split, label, dtype, src in items:
            name = f"{src.stem}.jpg" if split == "refs" else (f"good_{src.stem}.jpg" if label == 0 else f"defect_{dtype}_{src.stem}.jpg")
            dst = args.out / cat / split / name
            orig, saved = save(src, dst)
            rows.append({"sample_path": dst.relative_to(args.out).as_posix(), "category": cat, "split": split,
                         "label": label, "defect_type": dtype,
                         "original_path": src.relative_to(data.root).as_posix(), "original_sha256": sha256(src),
                         "original_size": orig, "saved_size": saved})
    with (args.out / "MANIFEST.csv").open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    (args.out / "LICENSE.md").write_text(LICENSE_TEXT.format(n=len(rows), max_side=MAX_SIDE, quality=JPEG_QUALITY))
    total = sum((args.out / r["sample_path"]).stat().st_size for r in rows)
    LOG.info("wrote %d images (%.2f MB) + MANIFEST.csv + LICENSE.md to %s", len(rows), total / 1e6, args.out)


if __name__ == "__main__":
    main()
