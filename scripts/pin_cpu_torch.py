"""Regenerate app/requirements.txt with CPU-only torch/torchvision pins for every Python version.

    python scripts/pin_cpu_torch.py --torch 2.14.1 --torchvision 0.29.1

Streamlit Community Cloud (Linux x86_64) must get the official ``+cpu`` wheels: the PyPI Linux wheels pull in
CUDA (several GB). We pin them by direct URL + SHA-256 — one line per CPython version that has a
``manylinux_2_28_x86_64`` +cpu wheel on https://download.pytorch.org/whl/cpu/<pkg>/ — instead of using
``--extra-index-url`` (uv's first-index rule would then refuse PyPI fallbacks on macOS).

Invariant (tested in tests/test_app_requirements.py): every platform/Python combination matches EXACTLY ONE
torch and one torchvision line. A catch-all PyPI line covers macOS, Windows, Linux aarch64 and any Linux
x86_64 Python without a +cpu wheel, so an unsupported Python fails loudly at install time instead of
silently skipping torch (the bug behind "ModuleNotFoundError: torch" on a Python 3.14 deployment).
"""

from __future__ import annotations

import argparse
import logging
import re
import urllib.request
from pathlib import Path

LOG = logging.getLogger("pin_cpu_torch")
INDEX = "https://download.pytorch.org/whl/cpu"
OTHER_DEPS = ["numpy>=1.24", "pillow>=10.0", "opencv-python-headless>=4.8", "scikit-learn>=1.3", "scipy>=1.10",
              "matplotlib>=3.7", "streamlit>=1.40"]
HEADER = """\
# Streamlit demo app — the ONLY dependency file Streamlit Community Cloud reads for this app (it checks the
# entrypoint's folder first). GENERATED by scripts/pin_cpu_torch.py — edit that script, not this file.
# CPU-only torch:
#  * Linux x86_64 (Community Cloud): official +cpu wheels by direct URL with SHA-256, one line per CPython
#    version ({versions}); no CUDA, ~200 MB.
#  * everything else (macOS, Windows, Linux aarch64, other Pythons): plain PyPI (CPU/MPS-only off Linux x86_64).
#    Every platform/Python matches exactly one torch line, so an unsupported Python fails loudly at install.
# No --extra-index-url: uv's first-index rule would then refuse PyPI fallbacks on macOS.
"""


def wheel_lines(pkg: str, version: str) -> tuple[list[str], list[str]]:
    with urllib.request.urlopen(f"{INDEX}/{pkg}/", timeout=60) as resp:  # fixed https URL
        html = resp.read().decode()
    pat = re.compile(rf'href="https://download(?:-r2)?\.pytorch\.org/whl/cpu/({re.escape(pkg)}-{re.escape(version)}'
                     r'%2Bcpu-cp3(\d+)-cp3\2-manylinux_2_28_x86_64\.whl#sha256=[0-9a-f]{64})"')
    found = {int(m.group(2)): m.group(1) for m in pat.finditer(html)}  # excludes free-threaded "t" builds
    if not found:
        raise SystemExit(f"no manylinux x86_64 +cpu wheels for {pkg}=={version} on {INDEX}/{pkg}/")
    pys = [f"3.{minor}" for minor in sorted(found)]
    lines = [f'{pkg} @ {INDEX}/{found[int(py[2:])]} ; sys_platform == "linux" and platform_machine == "x86_64" '
             f'and python_version == "{py}"' for py in pys]
    covered = " and ".join(f'python_version != "{py}"' for py in pys)
    lines.append(f'{pkg}=={version} ; sys_platform != "linux" or platform_machine != "x86_64" or ({covered})')
    return lines, pys


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    ap = argparse.ArgumentParser(description="Regenerate app/requirements.txt CPU-only torch pins")
    ap.add_argument("--torch", default="2.14.1")
    ap.add_argument("--torchvision", default="0.29.1")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[1] / "app" / "requirements.txt")
    args = ap.parse_args()
    torch_lines, torch_pys = wheel_lines("torch", args.torch)
    tv_lines, tv_pys = wheel_lines("torchvision", args.torchvision)
    if torch_pys != tv_pys:
        LOG.warning("torch covers %s but torchvision covers %s", torch_pys, tv_pys)
    text = HEADER.format(versions=", ".join(torch_pys)) + "\n".join(torch_lines + tv_lines + OTHER_DEPS) + "\n"
    args.out.write_text(text)
    LOG.info("wrote %s (CPU wheels for Python %s)", args.out, ", ".join(torch_pys))


if __name__ == "__main__":
    main()
